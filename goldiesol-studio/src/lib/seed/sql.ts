import { seed, SEED_TEAM_ID } from './index';

function literal(v: unknown): string {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'null';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (Array.isArray(v)) {
    if (v.length === 0) return `'{}'`;
    return `array[${v.map(literal).join(', ')}]`;
  }
  if (typeof v === 'object') return `${quote(JSON.stringify(v))}::jsonb`;
  return quote(String(v));
}

const quote = (s: string) => `'${s.replace(/'/g, "''")}'`;

// designs.current_version_id points at design_versions, which reference designs;
// the FK is deferrable, so everything goes in one transaction with constraints deferred.
export function buildSeedSql(): string {
  const lines = [
    '-- GENERATED by `npm run db:seed-sql` from src/lib/seed. Do not edit by hand.',
    'begin;',
    'set constraints all deferred;',
    `insert into public.teams (id, name) values (${quote(SEED_TEAM_ID)}, 'Goldiesol') on conflict (id) do nothing;`,
  ];
  for (const [table, rows] of Object.entries(seed)) {
    lines.push('', `-- ${table}`);
    for (const row of rows as readonly object[]) {
      const cols = ['team_id', ...Object.keys(row)];
      const vals = [quote(SEED_TEAM_ID), ...Object.values(row).map(literal)];
      lines.push(`insert into public.${table} (${cols.join(', ')}) values (${vals.join(', ')}) on conflict (id) do nothing;`);
    }
  }
  lines.push('', 'commit;', '');
  return lines.join('\n');
}
